export const DEFAULT_MATERIALS = LEGACY_COLORS.anthracite

export function findMaterial(list, id) {
  return list.find((entry) => entry.id === id) ?? list[0]
}

// Materijal sa RAL bojom umesto fabričke. Id dobija sufiks, pa keš
// tekstura u PatternMesh-u drži obe varijante odvojeno.
export function tinted(spec, ralId) {
  const ral = spec?.tintable ? findRal(ralId) : null
  if (!ral) return spec
  return { ...spec, id: `${spec.id}@${ral.id}`, color: ral.hex, ral: ral.id }
}

export function resolveMaterials(source) {
  const legacy = LEGACY_COLORS[source?.colorId] ?? DEFAULT_MATERIALS
  return {
    wallMaterialId: known(WALL_MATERIALS, source?.wallMaterialId, legacy.wall),
    roofMaterialId: known(ROOF_MATERIALS, source?.roofMaterialId, legacy.roof),
    doorMaterialId: known(DOOR_MATERIALS, source?.doorMaterialId, legacy.door),
    wallColor: findRal(source?.wallColor) ? source.wallColor : null,
    roofColor: findRal(source?.roofColor) ? source.roofColor : null,
    doorColor: findRal(source?.doorColor) ? source.doorColor : null,
  }
}

// Sve što 3D prikaz traži od scene, na jednom mestu.
export function sceneMaterials(scene) {
  return {
    wallMaterial: tinted(findMaterial(WALL_MATERIALS, scene.wallMaterialId), scene.wallColor),
    roofMaterial: tinted(findMaterial(ROOF_MATERIALS, scene.roofMaterialId), scene.roofColor),
    doorMaterial: tinted(findMaterial(DOOR_MATERIALS, scene.doorMaterialId), scene.doorColor),
    floorMaterial: findMaterial(FLOOR_FINISHES, scene.floor),
  }
}

function known(list, id, fallback) {
  return list.some((entry) => entry.id === id) ? id : fallback
}
